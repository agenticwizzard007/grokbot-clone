import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { shellFixture } from './shell-fixture.mjs';
import { preparePbeState } from '../paper-pbe-states.mjs';
import { inspectAlignment } from '../layout-alignment-ui.mjs';
const server = await shellFixture();
const output = path.resolve('.context/ui-custom/e-shell'); fs.mkdirSync(output, { recursive: true });
const results = [], markers = new Set();
const pass = name => { results.push({ name, pass: true }); console.log(`PASS ${name}`); };
async function scan(page) {
  const ids = await page.locator('[data-ui-id]').evaluateAll(nodes => nodes.map(node => node.dataset.uiId));
  assert.equal(ids.length, new Set(ids).size, 'no duplicate markers in the mounted DOM');
  ids.forEach(id => markers.add(id));
}
try {
  const page = await server.page(1280);
  await server.open(page, '#bots'); await scan(page);
  const defaults = (await server.api.request(server.account, 'GET', '/config')).body.doc;
  const added = await server.patch([{ op: 'add', path: '/dashboards/-', value: { id: '$new1', name: 'Weekly overview and planning', icon: 'layout-dashboard', widgets: [] } }]);
  const id = added.doc.dashboards[0].id;
  await server.patch([
    { op: 'replace', path: '/layout/sidebar/order', value: ['settings', 'files', 'dashboards', 'tasks', 'yourBots', 'createBot', 'usage', 'allBots'] },
    { op: 'replace', path: '/layout/sidebar/hidden', value: ['files', 'usage'] },
    { op: 'replace', path: '/layout/sidebar/width', value: 'wide' },
    { op: 'replace', path: '/layout/pinned', value: [{ type: 'dashboard', id }, { type: 'bot', id: server.fixture.bot.id }] },
  ]);
  await page.getByRole('region', { name: 'Pinned', exact: true }).waitFor();
  assert.equal(await page.locator('.sidebar').getByRole('button', { name: 'Files', exact: true }).count(), 0);
  const order = await page.locator('.sidebar__custom-scroll').evaluate(el => [...el.children].map(child => child.getAttribute('aria-label') || child.className));
  assert.equal(order[0], 'Pinned'); assert.ok(order[1].includes('sidebar__footer')); assert.equal(order[2], 'Dashboards');
  await page.waitForFunction(() => Math.round(document.querySelector('.sidebar').getBoundingClientRect().width) === 320);
  pass('sidebar ordering, hidden items, width and Pinned group');
  await page.getByRole('region', { name: 'Dashboards', exact: true }).getByRole('button', { name: 'Weekly overview and planning', exact: true }).click();
  await page.waitForURL(`**/#dash/${id}`); pass('dashboard sidebar route');
  await server.patch([{ op: 'replace', path: '/layout/sidebar/collapsed', value: true }]);
  await page.locator('.sidebar.is-collapsed').waitFor();
  await page.getByRole('button', { name: 'Expand sidebar', exact: true }).click();
  assert.equal(await page.locator('.sidebar.is-collapsed').count(), 0);
  await server.patch([{ op: 'replace', path: '/layout/sidebar/collapsed', value: false }]);
  pass('collapsed preference applies once and manual expansion works');
  await page.evaluate(async () => {
    const { useCustomization } = await import('/src/customization/store.ts');
    const doc = structuredClone(useCustomization.getState().effective);
    doc.layout.sidebar.order = ['tasks']; doc.layout.sidebar.hidden = ['settings']; doc.layout.phoneTabs = ['tasks'];
    doc.layout.pinned = [{ type: 'bot', id: 'missing' }, { type: 'dashboard', id: 'd_missing1' }];
    useCustomization.setState({ effective: doc });
  });
  assert.ok(await page.getByRole('button', { name: 'Account & settings' }).isVisible());
  assert.equal(await page.getByRole('region', { name: 'Pinned', exact: true }).count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => { location.hash = '#bots'; }); await page.locator('.phone-tabs').waitFor();
  assert.ok(await page.locator('.phone-tabs').getByRole('button', { name: 'Settings', exact: true }).isVisible());
  assert.ok(await page.locator('.phone-tabs button').count() >= 3); await scan(page);
  pass('render guards keep Settings and ignore dangling pins');
  // Restore through the real API so later checks use the regular store path.
  await server.patch([{ op: 'replace', path: '/layout', value: defaults.layout }]);
  await page.setViewportSize({ width: 1280, height: 900 });
  await server.open(page, `#bot/${server.fixture.bot.id}`); await scan(page);
  await preparePbeState(page, 'approval', server.fixture.bot.id);
  await server.patch([{ op: 'add', path: '/components/chat.runLog', value: 'hide' }]);
  await page.getByRole('button', { name: /Run log/ }).waitFor({ state: 'detached' });
  assert.ok(await page.getByText('Send an email?', { exact: true }).isVisible());
  pass('hidden run log preserves approval cards');
  await server.patch([{ op: 'add', path: '/components/chat.runLog', value: 'show' }]);
  await page.getByRole('button', { name: /Run log/ }).waitFor();
  assert.equal(await page.getByRole('button', { name: /Run log/ }).getAttribute('aria-expanded'), 'true');
  await server.patch([{ op: 'add', path: '/components/chat.runLog', value: 'collapsed' }]);
  await page.waitForFunction(() => document.querySelector('.steps__toggle')?.getAttribute('aria-expanded') === 'false');
  pass('show and collapsed run log states');
  await server.patch(['chat.avatars', 'chat.safetyNote', 'chat.modelChip', 'header.voiceButton', 'sidebar.search', 'sidebar.usage', 'sidebar.account'].map(id => ({ op: 'add', path: `/components/${id}`, value: 'hide' })));
  await page.locator('.chat__voice').waitFor({ state: 'detached' });
  for (const selector of ['.agent-message__heading > .bot-avatar', '.composer__note', '.model-pill__name', '.sidebar__search', '.sidebar-usage']) assert.equal(await page.locator(selector).first().isVisible(), false, selector);
  assert.ok(await page.locator('.composer__input').isVisible());
  assert.ok(await page.getByRole('button', { name: /^Model:/ }).isVisible());
  await page.getByRole('button', { name: 'Account & settings', exact: true }).click();
  assert.ok(await page.getByRole('menuitem', { name: /^Log out/ }).isVisible());
  await page.keyboard.press('Escape');
  assert.deepEqual(await page.evaluate(inspectAlignment), []);
  pass('optional chat and sidebar chrome hides without losing composer, picker or sign out');
  await server.patch(['bots.statusChips', 'bots.roomsSection', 'tasks.filters', 'phone.tabLabels'].map(id => ({ op: 'add', path: `/components/${id}`, value: 'hide' })));
  await server.open(page, '#bots');
  assert.equal(await page.getByRole('heading', { name: 'Rooms', exact: true }).count(), 0);
  assert.equal(await page.locator('.pb-bot-card__identity > .pb-pill:visible').count(), 0);
  assert.deepEqual(await page.evaluate(inspectAlignment), []); pass('Bots hide states leave no orphan heading or gap');
  await server.open(page, '#tasks');
  assert.equal(await page.locator('.task-filters').isVisible(), false);
  assert.ok(await page.getByTestId('tasks-needs-input').isVisible());
  assert.deepEqual(await page.evaluate(inspectAlignment), []); pass('task filters hide while approvals stay visible');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.phone-tabs').waitFor();
  assert.equal(await page.locator('.phone-tabs span:visible').count(), 0);
  assert.ok(await page.locator('.phone-tabs').getByRole('button', { name: 'Settings', exact: true }).isVisible());
  pass('icon-only phone tabs keep accessible names');
  await server.patch([{ op: 'replace', path: '/components', value: {} }, { op: 'replace', path: '/layout/home', value: { kind: 'dashboard', dashboardId: id } }]);
  await server.open(page); await page.waitForURL(`**/#dash/${id}`); pass('dashboard home redirect');
  const fallback = await page.evaluate(async () => {
    const { homeScreen } = await import('/src/customization/layout/useHome.ts');
    const { useCustomization } = await import('/src/customization/store.ts');
    const doc = structuredClone(useCustomization.getState().effective); doc.dashboards = [];
    return homeScreen(doc);
  });
  assert.equal(fallback, null); pass('deleted dashboard home falls back to default');
  await server.patch([{ op: 'replace', path: '/layout/home', value: { kind: 'default' } }]);
  await server.open(page); await page.waitForURL('**/#bots');
  await page.setViewportSize({ width: 1280, height: 900 });
  await server.open(page, `#bot/${server.fixture.bot.id}`);
  await server.open(page); await page.waitForURL('**/#bot/**'); pass('default home stays Bots on phone and last chat on desktop');
  await server.patch([{ op: 'replace', path: '/keybindings', value: { search: 'Alt+S', settings: 'Alt+O', goBots: 'Alt+B', goTasks: 'Alt+T', goDashboard1: 'Alt+D' } }]);
  await page.waitForFunction(async () => (await import('/src/lib/shortcuts.ts')).shortcutLabel('search', false) === 'Alt+S');
  assert.match(await page.locator('.sidebar__search').getAttribute('title'), /Alt\+S/);
  await page.keyboard.press('Control+k'); assert.equal(await page.locator('.search-modal').isVisible(), false);
  await page.keyboard.press('Alt+s'); await page.waitForURL('**/#search');
  await page.keyboard.press('Alt+o'); await page.waitForURL('**/#settings');
  await page.keyboard.press('Alt+t'); await page.waitForURL('**/#tasks');
  await page.keyboard.press('Alt+b'); await page.waitForURL('**/#bots');
  await page.keyboard.press('Alt+d'); await page.waitForURL(`**/#dash/${id}`);
  pass('custom shortcuts navigate and old bindings stop; tooltip updates');
  await server.open(page, '#settings/general');
  await page.getByRole('button', { name: 'View', exact: true }).click();
  assert.match(await page.locator('#general-shortcuts').innerText(), /Alt\s*S/); pass('Settings shortcut labels reflect effective bindings');
  const registry = await server.api.request(server.account, 'GET', '/schema');
  const componentIds = registry.body.registries?.components?.map(entry => entry.id) ?? registry.body.registry?.components?.map(entry => entry.id);
  if (componentIds) assert.deepEqual([...markers].sort(), componentIds.sort());
  else assert.equal(markers.size, 12);
  pass('all 12 registry markers observed once per mounted DOM');
  await page.screenshot({ path: path.join(output, 'shortcuts.png') });
  fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify({ passed: results.length, failed: 0, results, markers: [...markers] }, null, 2));
  console.log(`PASS shell customization: ${results.length} cases, 0 failures. ${output}/report.json`);
} finally { await server.close(); }
