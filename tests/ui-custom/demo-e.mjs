import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { shellFixture } from './shell-fixture.mjs';
const server = await shellFixture();
const output = path.resolve('.context/ui-custom/demo-e'); fs.mkdirSync(output, { recursive: true });
const results = [], screenshots = [];
const shot = async (page, name) => { const file = path.join(output, `${name}.png`); await page.screenshot({ path: file }); screenshots.push(file); };
try {
  const desktop = await server.page(1280), phone = await server.page(390);
  await server.open(desktop, `#bot/${server.fixture.bot.id}`); await server.open(phone, '#bots');
  await shot(desktop, 'desktop-before'); await shot(phone, 'phone-before');
  const exampleC = [{ op: 'add', path: '/components/sidebar.usage', value: 'hide' }, { op: 'add', path: '/components/chat.runLog', value: 'collapsed' }];
  const exampleD = [{ op: 'replace', path: '/layout/home', value: { kind: 'tasks' } }, { op: 'replace', path: '/layout/phoneTabs', value: ['tasks', 'bots', 'search', 'settings'] }];
  const c = await server.patch(exampleC);
  await desktop.locator('.sidebar-usage').waitFor({ state: 'detached' });
  results.push({ name: 'Example C applied through API', revision: c.revision, pass: true });
  const d = await server.patch(exampleD);
  await phone.waitForFunction(() => document.querySelector('.phone-tabs button')?.getAttribute('aria-label') === 'Tasks');
  assert.deepEqual(await phone.locator('.phone-tabs button').allTextContents(), ['Tasks', 'Bots', 'Search', 'Settings']);
  results.push({ name: 'Example D phone tab order', revision: d.revision, pass: true });
  await server.open(phone); await phone.waitForURL('**/#tasks');
  await server.open(desktop); await desktop.waitForURL('**/#tasks');
  results.push({ name: 'home opens Tasks at 390 and 1280', pass: true });
  await phone.locator('.task-card').first().waitFor(); await desktop.locator('.task-card').first().waitFor();
  await shot(phone, 'phone-after'); await shot(desktop, 'desktop-after');
  await server.open(desktop, `#bot/${server.fixture.bot.id}`); await desktop.locator('.composer__input').waitFor();
  assert.match(new URL(desktop.url()).hash, /^#bot\//);
  results.push({ name: 'explicit chat hash wins over home', pass: true });
  await server.patch([{ op: 'add', path: '/keybindings/focusComposer', value: 'Alt+J' }]);
  await desktop.waitForFunction(async () => (await import('/src/lib/shortcuts.ts')).shortcutLabel('focus', false) === 'Alt+J');
  await desktop.locator('.shell-header').focus();
  assert.equal(await desktop.locator('.shell-header').evaluate(el => el === document.activeElement), true);
  await desktop.keyboard.press('Control+i');
  assert.equal(await desktop.locator('.composer__input').evaluate(el => el === document.activeElement), false);
  await desktop.keyboard.press('Alt+j');
  assert.equal(await desktop.locator('.composer__input').evaluate(el => el === document.activeElement), true);
  results.push({ name: 'Alt+J focuses composer and old Ctrl+I stops', pass: true });
  await shot(desktop, 'composer-alt-j');
  const final = await server.api.request(server.account, 'GET', '/config');
  fs.writeFileSync(path.join(output, 'demo.json'), JSON.stringify({ passed: results.length, failed: 0, results, screenshots, doc: final.body.doc }, null, 2));
  console.log(`PASS UC-E demo: ${results.length} cases, 0 failures. ${output}/demo.json`);
  console.log(screenshots.join('\n'));
} finally { await server.close(); }
