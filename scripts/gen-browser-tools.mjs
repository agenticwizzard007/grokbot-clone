#!/usr/bin/env node
// Regenerates server/src/computers/browser-tools.ts: the Playwright MCP browser tools Bots get on
// cloud VMs, with their exact schemas from the pinned @playwright/mcp (keep it in step with
// infra/vm-image/Dockerfile). Run after changing the version: node scripts/gen-browser-tools.mjs
import { spawn } from 'node:child_process';
import fs from 'node:fs';

// The browser tools Bots may use. Left out on purpose: browser_run_code_unsafe (runs code inside the
// Playwright process, next to the VM's companion), browser_close (would close the Bot's visible Chrome),
// and debugging/emulation tools that only add noise.
const ALLOW = [
  'browser_navigate', 'browser_navigate_back', 'browser_snapshot', 'browser_click', 'browser_type', 'browser_fill_form',
  'browser_select_option', 'browser_press_key', 'browser_hover', 'browser_drag', 'browser_file_upload', 'browser_handle_dialog',
  'browser_tabs', 'browser_wait_for', 'browser_take_screenshot', 'browser_find', 'browser_evaluate', 'browser_console_messages',
];

const cli = new URL('../node_modules/@playwright/mcp/cli.js', import.meta.url).pathname;
const version = JSON.parse(fs.readFileSync(new URL('../node_modules/@playwright/mcp/package.json', import.meta.url), 'utf8')).version;
const p = spawn(process.execPath, [cli, '--cdp-endpoint', 'http://127.0.0.1:1'], { stdio: ['pipe', 'pipe', 'inherit'] });
let buf = '';
const waiters = new Map();
p.stdout.on('data', (d) => {
  buf += d;
  for (let i; (i = buf.indexOf('\n')) >= 0;) { const line = buf.slice(0, i); buf = buf.slice(i + 1); if (line.trim()) { const m = JSON.parse(line); waiters.get(m.id)?.(m); } }
});
let id = 0;
const rpc = (method, params) => new Promise((r) => { const i = ++id; waiters.set(i, r); p.stdin.write(JSON.stringify({ jsonrpc: '2.0', id: i, method, params }) + '\n'); });
await rpc('initialize', { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'swarm', version: '1' } });
p.stdin.write(JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized' }) + '\n');
const all = (await rpc('tools/list', {})).result.tools;
p.kill();
const tools = ALLOW.map((name) => {
  const t = all.find((x) => x.name === name);
  if (!t) throw new Error(`@playwright/mcp ${version} has no tool ${name}`);
  return { name: t.name, description: t.description, parameters: t.inputSchema };
});
const strip = ({ $schema, ...rest }) => rest; // providers reject a $schema key in function parameters
const out = new URL('../server/src/computers/browser-tools.ts', import.meta.url);
fs.writeFileSync(out, `// Generated by scripts/gen-browser-tools.mjs from @playwright/mcp@${version}. Do not edit by hand.\n` +
  `// The Playwright browser tools Bots get on cloud VMs (see companion --multi and computers/cloudvm.ts).\n` +
  `export const BROWSER_TOOLS_VERSION = ${JSON.stringify(version)};\n` +
  `export const BROWSER_TOOLS: { name: string; description: string; parameters: Record<string, unknown> }[] = ${JSON.stringify(tools.map((t) => ({ ...t, parameters: strip(t.parameters) })), null, 2)};\n`);
console.log(`wrote ${tools.length} tools from @playwright/mcp@${version}`);
process.exit(0);
